/* ===================== 显示控制 ===================== */

void oled_clear(void)
{
    memset(oled_buf, 0x00, sizeof(oled_buf));
    oled_refresh();
}

void oled_fill(uint8_t pattern)
{
    memset(oled_buf, pattern, sizeof(oled_buf));
    oled_refresh();
}

void oled_set_pos(uint8_t x, uint8_t page)
{
    oled_write_cmd(0xB0 + page);
    oled_write_cmd(0x00 + (x & 0x0F));
    oled_write_cmd(0x10 + ((x >> 4) & 0x0F));
}

void oled_display_on(void)
{
    oled_write_cmd(0x8D);
    oled_write_cmd(0x14);
    oled_write_cmd(0xAF);
}

void oled_display_off(void)
{
    oled_write_cmd(0xAE);
    oled_write_cmd(0x8D);
    oled_write_cmd(0x10);
}

/* ===================== 缓冲区刷新 ===================== */

void oled_refresh(void)
{
    uint8_t page, col;
    for (page = 0; page < OLED_PAGES; page++)
    {
        oled_set_pos(0, page);
        for (col = 0; col < OLED_WIDTH; col++)
        {
            oled_write_data(oled_buf[page * OLED_WIDTH + col]);
        }
    }
}

/* ===================== 基本绘图 ===================== */

void oled_draw_pixel(uint8_t x, uint8_t y, uint8_t on)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    if (on)
        oled_buf[(y / 8) * OLED_WIDTH + x] |= (1 << (y % 8));
    else
        oled_buf[(y / 8) * OLED_WIDTH + x] &= ~(1 << (y % 8));
}

void oled_draw_char(uint8_t x, uint8_t page, char ch)
{
    uint8_t i;
    if (ch < ' ' || ch > '~') return;
    if (x > OLED_WIDTH - 6) return;

    for (i = 0; i < 6; i++)
        oled_buf[page * OLED_WIDTH + x + i] = font_6x12[ch - ' '][i];

    if (page + 1 < OLED_PAGES)
        for (i = 0; i < 6; i++)
            oled_buf[(page + 1) * OLED_WIDTH + x + i] = font_6x12[ch - ' '][i + 6];
}

/*
 * 绘制 ASCII 字符，支持 Y 方向像素偏移
 * y_offset: 向下偏移像素数 (0~7)
 * 用于混合行中对齐 16x16 汉字基线 (汉字像素从第2行开始)
 */
void oled_draw_char_offset(uint8_t x, uint8_t page, char ch, uint8_t y_offset)
{
    uint8_t i;
    if (ch < ' ' || ch > '~') return;
    if (x > OLED_WIDTH - 6) return;
    if (y_offset >= 8) return;
    if (y_offset == 0) {
        oled_draw_char(x, page, ch);
        return;
    }

    /* 将 12px 字体下移 y_offset 像素 */
    for (i = 0; i < 6; i++) {
        uint8_t lo = font_6x12[ch - ' '][i];
        uint8_t hi = font_6x12[ch - ' '][i + 6];
        /* 合并上下两部分，下移 y_offset 位 */
        uint16_t combined = ((uint16_t)hi << 8) | lo;
        combined <<= y_offset;
        if (page < OLED_PAGES)
            oled_buf[page * OLED_WIDTH + x + i] |= (uint8_t)(combined & 0xFF);
        if (page + 1 < OLED_PAGES)
            oled_buf[(page + 1) * OLED_WIDTH + x + i] |= (uint8_t)((combined >> 8) & 0xFF);
    }
}

void oled_draw_string(uint8_t x, uint8_t page, const char *str)
{
    uint8_t cx = x;
    while (*str)
    {
        if (cx > OLED_WIDTH - 6) break;
        oled_draw_char(cx, page, *str);
        cx += 6;
        str++;
    }
}

