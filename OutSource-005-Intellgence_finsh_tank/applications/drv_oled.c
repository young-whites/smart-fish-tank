/* ===================== GPIO 底层操作 (CMSIS 寄存器) ===================== */
#define SCL_PIN  12  /* PA12 */
#define SDA_PIN  11  /* PA11 */

static inline void scl_high(void) { GPIOA->BSRR = (1U << SCL_PIN); }
static inline void scl_low(void)  { GPIOA->BRR  = (1U << SCL_PIN); }
static inline void sda_high(void) { GPIOA->BSRR = (1U << SDA_PIN); }
static inline void sda_low(void)  { GPIOA->BRR  = (1U << SDA_PIN); }

static inline void i2c_delay(void)
{
    volatile uint8_t i = 5;
    while (i--);
}

void oled_gpio_init(void)
{
    /* 使能 GPIOA 时钟 */
    RCC->APB2ENR |= RCC_APB2ENR_IOPAEN;

    /* PA11(SDA) 和 PA12(SCL): 推挽输出 50MHz
     * CRL: PA0-PA7,  CRH: PA8-PA15
     * PA11 -> CRH[15:12], PA12 -> CRH[19:16]
     * MODE=0b11 (50MHz), CNF=0b00 (推挽输出)
     */
    GPIOA->CRH &= ~((0xFU << 12) | (0xFU << 16));  /* 清除 PA11, PA12 配置 */
    GPIOA->CRH |=  ((0x3U << 12) | (0x3U << 16));  /* MODE=11, CNF=00 */

    /* 初始状态: SCL=HIGH, SDA=HIGH */
    scl_high();
    sda_high();
}

/* ===================== 软件 I2C 协议 ===================== */

void oled_i2c_start(void)
{
    sda_high();
    scl_high();
    i2c_delay();
    sda_low();
    i2c_delay();
    scl_low();
    i2c_delay();
}

void oled_i2c_stop(void)
{
    sda_low();
    scl_high();
    i2c_delay();
    sda_high();
    i2c_delay();
}

void oled_i2c_ack(void)
{
    scl_low();
    sda_high();
    i2c_delay();
    scl_high();
    i2c_delay();
    scl_low();
    i2c_delay();
}

void oled_i2c_send_byte(uint8_t data)
{
    uint8_t i;
    for (i = 0; i < 8; i++)
    {
        scl_low();
        if (data & 0x80)
            sda_high();
        else
            sda_low();
        data <<= 1;
        i2c_delay();
        scl_high();
        i2c_delay();
    }
    scl_low();
    oled_i2c_ack();
}

/* ===================== OLED 命令/数据 ===================== */

void oled_write_cmd(uint8_t cmd)
{
    oled_i2c_start();
    oled_i2c_send_byte(OLED_I2C_ADDR);
    oled_i2c_send_byte(0x00);
    oled_i2c_send_byte(cmd);
    oled_i2c_stop();
}

void oled_write_data(uint8_t data)
{
    oled_i2c_start();
    oled_i2c_send_byte(OLED_I2C_ADDR);
    oled_i2c_send_byte(0x40);
    oled_i2c_send_byte(data);
    oled_i2c_stop();
}

