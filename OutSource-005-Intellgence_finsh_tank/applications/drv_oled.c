/* ===================== GPIO 底层操作 ===================== */

static inline void scl_high(void) { HAL_GPIO_WritePin(OLED_SCL_PORT, OLED_SCL_PIN, GPIO_PIN_SET); }
static inline void scl_low(void)  { HAL_GPIO_WritePin(OLED_SCL_PORT, OLED_SCL_PIN, GPIO_PIN_RESET); }
static inline void sda_high(void) { HAL_GPIO_WritePin(OLED_SDA_PORT, OLED_SDA_PIN, GPIO_PIN_SET); }
static inline void sda_low(void)  { HAL_GPIO_WritePin(OLED_SDA_PORT, OLED_SDA_PIN, GPIO_PIN_RESET); }

static inline void i2c_delay(void)
{
    volatile uint8_t i = 5;
    while (i--);
}

void oled_gpio_init(void)
{
    GPIO_InitTypeDef gpio = {0};

    /* 使能 GPIOA 时钟 */
    __HAL_RCC_GPIOA_CLK_ENABLE();

    /* 配置 PA11(SDA) 和 PA12(SCL) 为推挽输出 */
    gpio.Pin   = OLED_SCL_PIN | OLED_SDA_PIN;
    gpio.Mode  = GPIO_MODE_OUTPUT_PP;
    gpio.Pull  = GPIO_NOPULL;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOA, &gpio);

    /* 初始状态: SCL=HIGH, SDA=HIGH */
    scl_high();
    sda_high();
}

/* ===================== 软件 I2C 协议 ===================== */

void oled_i2c_start(void)
{
    sda_high();
    scl_high();
    i2c_delay();
    sda_low();
    i2c_delay();
    scl_low();
    i2c_delay();
}

void oled_i2c_stop(void)
{
    sda_low();
    scl_high();
    i2c_delay();
    sda_high();
    i2c_delay();
}

void oled_i2c_ack(void)
{
    scl_low();
    sda_high();     /* 释放 SDA, 等待从机 ACK */
    i2c_delay();
    scl_high();
    i2c_delay();
    scl_low();
    i2c_delay();
}

void oled_i2c_send_byte(uint8_t data)
{
    uint8_t i;
    for (i = 0; i < 8; i++)
    {
        scl_low();
        if (data & 0x80)
            sda_high();
        else
            sda_low();
        data <<= 1;
        i2c_delay();
        scl_high();
        i2c_delay();
    }
    scl_low();
    oled_i2c_ack();
}

/* ===================== OLED 命令/数据 ===================== */

void oled_write_cmd(uint8_t cmd)
{
    oled_i2c_start();
    oled_i2c_send_byte(OLED_I2C_ADDR);   /* 从机地址 + 写 */
    oled_i2c_send_byte(0x00);             /* Co=0, D/C#=0 (命令) */
    oled_i2c_send_byte(cmd);
    oled_i2c_stop();
}

void oled_write_data(uint8_t data)
{
    oled_i2c_start();
    oled_i2c_send_byte(OLED_I2C_ADDR);   /* 从机地址 + 写 */
    oled_i2c_send_byte(0x40);             /* Co=0, D/C#=1 (数据) */
    oled_i2c_send_byte(data);
    oled_i2c_stop();
}

/* ===================== OLED 驱动初始化 ===================== */

void oled_init(void)
{
    oled_gpio_init();

    /* SSD1306 初始化序列 */
    oled_write_cmd(0xAE);   /* 关显示 */
    oled_write_cmd(0xD5);   /* 设置时钟分频 */
    oled_write_cmd(0x80);   /* 默认分频 */
    oled_write_cmd(0xA8);   /* 设置多路复用率 */
    oled_write_cmd(0x3F);   /* 64 行 */
    oled_write_cmd(0xD3);   /* 设置显示偏移 */
    oled_write_cmd(0x00);   /* 无偏移 */
    oled_write_cmd(0x40);   /* 设置起始行 = 0 */
    oled_write_cmd(0x8D);   /* 电荷泵 */
    oled_write_cmd(0x14);   /* 开启电荷泵 */
    oled_write_cmd(0x20);   /* 内存地址模式 */
    oled_write_cmd(0x02);   /* 页地址模式 */
    oled_write_cmd(0xA1);   /* 段重映射 (列127=mapped to SEG0) */
    oled_write_cmd(0xC8);   /* COM 输出扫描方向: 从 COM[N-1] 到 COM0 */
    oled_write_cmd(0xDA);   /* COM 引脚硬件配置 */
    oled_write_cmd(0x12);   /* 默认配置 */
    oled_write_cmd(0x81);   /* 设置对比度 */
    oled_write_cmd(0xCF);   /* 对比度值 */
    oled_write_cmd(0xD9);   /* 预充电周期 */
    oled_write_cmd(0xF1);   /* 默认值 */
    oled_write_cmd(0xDB);   /* VCOMH 取消选择电平 */
    oled_write_cmd(0x40);   /* 默认值 */
    oled_write_cmd(0xA4);   /* 全局显示开启 (输出跟随 RAM) */
    oled_write_cmd(0xA6);   /* 正常显示 (非反色) */
    oled_write_cmd(0xAF);   /* 开显示 */

    /* 清屏 */
    oled_clear();

    LOG_I("OLED SSD1306 initialized (SDA=PA11, SCL=PA12)");
}

/* ===================== 显示控制 ===================== */

void oled_clear(void)
{
    memset(oled_buf, 0x00, sizeof(oled_buf));
    oled_refresh();
}

void oled_fill(uint8_t pattern)
{
    memset(oled_buf, pattern, sizeof(oled_buf));
    oled_refresh();
}

void oled_set_pos(uint8_t x, uint8_t page)
{
    oled_write_cmd(0xB0 + page);         /* 页地址 */
    oled_write_cmd(0x00 + (x & 0x0F));   /* 列地址低 4 位 */
    oled_write_cmd(0x10 + ((x >> 4) & 0x0F)); /* 列地址高 4 位 */
}

void oled_display_on(void)
{
    oled_write_cmd(0x8D);  /* 电荷泵 */
    oled_write_cmd(0x14);  /* 开启 */
    oled_write_cmd(0xAF);  /* 开显示 */
}

void oled_display_off(void)
{
    oled_write_cmd(0xAE);  /* 关显示 */
    oled_write_cmd(0x8D);  /* 电荷泵 */
    oled_write_cmd(0x10);  /* 关闭 */
}

/* ===================== 缓冲区刷新 ===================== */

void oled_refresh(void)
{
    uint8_t page, col;
    for (page = 0; page < OLED_PAGES; page++)
    {
        oled_set_pos(0, page);
        for (col = 0; col < OLED_WIDTH; col++)
        {
            oled_write_data(oled_buf[page * OLED_WIDTH + col]);
        }
    }
}

/* ===================== 基本绘图 ===================== */

void oled_draw_pixel(uint8_t x, uint8_t y, uint8_t on)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    if (on)
        oled_buf[(y / 8) * OLED_WIDTH + x] |= (1 << (y % 8));
    else
        oled_buf[(y / 8) * OLED_WIDTH + x] &= ~(1 << (y % 8));
}

void oled_draw_char(uint8_t x, uint8_t page, char ch)
{
    uint8_t i;

    if (ch < ' ' || ch > '~') return;  /* 非可打印字符 */
    if (x > OLED_WIDTH - 6) return;     /* 超出屏幕宽度 */

    /* 字体 6x12, 分上下两半各 6 字节 */
    /* 上半部分 (page N) */
    for (i = 0; i < 6; i++)
    {
        oled_buf[page * OLED_WIDTH + x + i] = font_6x12[ch - ' '][i];
    }
    /* 下半部分 (page N+1) */
    if (page + 1 < OLED_PAGES)
    {
        for (i = 0; i < 6; i++)
        {
            oled_buf[(page + 1) * OLED_WIDTH + x + i] = font_6x12[ch - ' '][i + 6];
        }
    }
}

void oled_draw_string(uint8_t x, uint8_t page, const char *str)
{
    uint8_t cx = x;
    while (*str)
    {
        if (cx > OLED_WIDTH - 6) break;
        oled_draw_char(cx, page, *str);
        cx += 6;
        str++;
    }
}

void oled_draw_number(uint8_t x, uint8_t page, int32_t num)
{
    char buf[12];
    if (num < 0)
    {
        oled_draw_char(x, page, '-');
        x += 6;
        num = -num;
    }
    if (num == 0)
    {
        oled_draw_char(x, page, '0');
        return;
    }
    /* 反向写入 */
    int i = 0;
    int32_t n = num;
    while (n > 0 && i < 10)
    {
        buf[i++] = '0' + (n % 10);
        n /= 10;
    }
    /* 正向绘制 */
    while (--i >= 0)
    {
        oled_draw_char(x, page, buf[i]);
        x += 6;
        if (x > OLED_WIDTH - 6) break;
    }
}

void oled_draw_float(uint8_t x, uint8_t page, float num, uint8_t decimal)
{
    char buf[16];
    switch (decimal)
    {
        case 1: snprintf(buf, sizeof(buf), "%.1f", num); break;
        case 2: snprintf(buf, sizeof(buf), "%.2f", num); break;
        case 3: snprintf(buf, sizeof(buf), "%.3f", num); break;
        default: snprintf(buf, sizeof(buf), "%.0f", num); break;
    }
    oled_draw_string(x, page, buf);
}

